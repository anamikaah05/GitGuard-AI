
"""
GitHub webhook endpoint for GitGuard AI.
Receives, verifies, and processes GitHub events.
"""

import hashlib
import hmac
import json
import logging

from fastapi import APIRouter, Request, HTTPException

from core.config import settings
from api.routes.pr_scan import perform_pr_scan
from utils.github import post_pr_comment, fetch_push_files
from scanner.scanner import run_rule_scan
from services.secret_service import predict_secret
from utils.github_checks import create_security_check
from services.scan_history_service import save_scan_history

logger = logging.getLogger(__name__)

router = APIRouter(
    prefix="/api/webhooks",
    tags=["GitHub Webhooks"],
)


def verify_github_signature(
    payload: bytes,
    signature: str | None,
) -> bool:
    """Verify that the webhook request was signed by GitHub."""

    if not settings.github_webhook_secret:
        logger.error("GitHub webhook secret is not configured.")
        return False

    if not signature or not signature.startswith("sha256="):
        return False

    expected_signature = "sha256=" + hmac.new(
        settings.github_webhook_secret.encode("utf-8"),
        payload,
        hashlib.sha256,
    ).hexdigest()

    return hmac.compare_digest(expected_signature, signature)


@router.post("/github")
async def receive_github_webhook(request: Request):
    """Receive, verify, and process GitHub events."""

    payload = await request.body()

    signature = request.headers.get("X-Hub-Signature-256")

    if not verify_github_signature(payload, signature):
        raise HTTPException(
            status_code=401,
            detail="Invalid GitHub webhook signature.",
        )

    event = request.headers.get("X-GitHub-Event", "unknown")

    try:
        data = json.loads(payload)
    except json.JSONDecodeError:
        raise HTTPException(
            status_code=400,
            detail="Invalid JSON payload.",
        )

    action = data.get("action")

    # --------------------------------------------------
    # PROCESS PULL REQUEST EVENTS
    # --------------------------------------------------

    if event == "pull_request":

        supported_actions = {"opened", "synchronize", "reopened"}

        if action not in supported_actions:
            return {
                "success": True,
                "event": event,
                "action": action,
                "message": "Pull Request action ignored.",
            }

        pull_request = data.get("pull_request", {})
        pr_url = pull_request.get("html_url")

        if not pr_url:
            raise HTTPException(
                status_code=400,
                detail="Pull Request URL is missing.",
            )

        logger.info(
            "Starting automatic PR scan: action=%s, url=%s",
            action,
            pr_url,
        )

        # Run complete Pull Request scan.
        scan_result = await perform_pr_scan(pr_url)

        # Generate GitGuard AI security report.

        secret_status = (
            "Potential secret detected"
            if scan_result.has_secret
            else "No secret detected"
        )

        risk_status = scan_result.pr_risk.risk_level

        comment = f"""
<!-- gitguard-ai-report -->

## GitGuard AI Security Report

### Secret Detection
- **Status:** {secret_status}
- **ML Prediction:** {scan_result.secret_scan.ml_prediction}
- **Confidence:** {scan_result.secret_scan.confidence:.2%}

### Pull Request Risk Analysis
- **Risk Level:** {risk_status}
- **Confidence:** {scan_result.pr_risk.confidence:.2%}

### Scan Summary
- **Files scanned:** {scan_result.files_scanned}
- **Files skipped:** {scan_result.files_skipped}
- **Rule-based findings:** {len(scan_result.secret_scan.rule_matches)}
- **Entropy findings:** {len(scan_result.secret_scan.entropy_flags)}

---
*Automated security report generated by GitGuard AI.*
"""

        # Post report on GitHub Pull Request.
        comment_result = await post_pr_comment(pr_url, comment)

        # --------------------------------------------------
        # SAVE PULL REQUEST SCAN TO DATABASE
        # --------------------------------------------------

        repository_name = data.get("repository", {}).get("full_name")

        save_result = save_scan_history(
            event_type="pull_request",
            repository=repository_name,
            action=action,
            branch=pull_request.get("head", {}).get("ref"),
            pr_url=pr_url,
            commit_sha=pull_request.get("head", {}).get("sha"),
            has_secret=scan_result.has_secret,
            ml_prediction=scan_result.secret_scan.ml_prediction,
            secret_confidence=scan_result.secret_scan.confidence,
            rule_findings=len(scan_result.secret_scan.rule_matches),
            entropy_findings=len(scan_result.secret_scan.entropy_flags),
            risk_level=scan_result.pr_risk.risk_level,
            risk_confidence=scan_result.pr_risk.confidence,
            files_scanned=scan_result.files_scanned,
            files_skipped=scan_result.files_skipped,
            scan_details=scan_result.model_dump(mode="json"),
        )

        logger.info("PR scan saved to database: %s", save_result)

        return {
            "success": True,
            "event": event,
            "action": action,
            "pr_url": pr_url,
            "scan_result": scan_result.model_dump(mode="json"),
            "comment_result": comment_result,
            "database_result": save_result,
            "message": "Pull Request scanned successfully.",
        }

    # --------------------------------------------------
    # PROCESS PUSH EVENTS
    # --------------------------------------------------

    if event == "push":

        repository = data.get("repository", {})
        repository_name = repository.get("full_name")

        before = data.get("before")
        after = data.get("after")
        branch = data.get("ref")

        logger.info(
            "Starting push security scan: repository=%s, branch=%s",
            repository_name,
            branch,
        )

        # Ignore branch creation or deletion events.

        if (
            not repository_name
            or not before
            or not after
            or before == "0" * 40
            or after == "0" * 40
        ):
            return {
                "success": True,
                "event": event,
                "message": "Push contains no comparable commits.",
            }

        # Fetch files changed by the push.

        files = await fetch_push_files(
            repository_name,
            before,
            after,
        )

        added_lines = []
        files_scanned = 0
        files_skipped = 0

        for file in files:

            patch = file.get("patch")

            if not patch:
                files_skipped += 1
                continue

            files_scanned += 1

            for line in patch.splitlines():

                if line.startswith("+") and not line.startswith("+++"):
                    added_lines.append(line[1:])

        code = "\n".join(added_lines)

        # Return if no added code is available.

        if not code.strip():
            return {
                "success": True,
                "event": event,
                "branch": branch,
                "files_scanned": files_scanned,
                "files_skipped": files_skipped,
                "has_secret": False,
                "message": "No added code available for secret scanning.",
            }

        # Run rule-based and ML secret detection.

        rule_result = run_rule_scan(code)
        ml_result = predict_secret(code)

        has_secret = ml_result.is_secret or rule_result.has_findings

        # --------------------------------------------------
        # CREATE GITHUB SECURITY CHECK
        # --------------------------------------------------

        summary = f"""
## GitGuard AI Push Security Report

- Repository: {repository_name}
- Branch: {branch}
- Files scanned: {files_scanned}
- Files skipped: {files_skipped}
- Potential secret detected: {has_secret}
- ML prediction: {ml_result.ml_label}
- ML confidence: {ml_result.confidence:.2%}
- Rule-based findings: {len(rule_result.rule_matches)}
- Entropy findings: {len(rule_result.entropy_flags)}

{"Potential secret detected. Please review the affected code and rotate any exposed credentials." if has_secret else "No potential secrets detected in the scanned additions."}
"""

        check_result = await create_security_check(
            repository_name=repository_name,
            commit_sha=after,
            has_secret=has_secret,
            summary=summary,
        )

        # --------------------------------------------------
        # SAVE PUSH SCAN TO DATABASE
        # --------------------------------------------------

        save_result = save_scan_history(
            event_type="push",
            repository=repository_name,
            branch=branch,
            commit_sha=after,
            has_secret=has_secret,
            ml_prediction=ml_result.ml_label,
            secret_confidence=ml_result.confidence,
            rule_findings=len(rule_result.rule_matches),
            entropy_findings=len(rule_result.entropy_flags),
            files_scanned=files_scanned,
            files_skipped=files_skipped,
            scan_details={
                "secret_scan": {
                    "ml_prediction": ml_result.ml_label,
                    "confidence": ml_result.confidence,
                    "rule_matches": rule_result.rule_matches,
                    "entropy_flags": rule_result.entropy_flags,
                },
                "check_result": check_result,
            },
        )

        logger.info("Push scan saved to database: %s", save_result)

        logger.info(
            "Push scan complete | secret=%s | files=%d",
            has_secret,
            files_scanned,
        )

        return {
            "success": True,
            "event": event,
            "branch": branch,
            "repository": repository_name,
            "check_result": check_result,
            "database_result": save_result,
            "files_scanned": files_scanned,
            "files_skipped": files_skipped,
            "has_secret": has_secret,
            "secret_scan": {
                "ml_prediction": ml_result.ml_label,
                "confidence": ml_result.confidence,
                "rule_matches": rule_result.rule_matches,
                "entropy_flags": rule_result.entropy_flags,
                "scanned_text_length": len(code),
            },
            "message": "Push security scan completed successfully.",
        }

    # --------------------------------------------------
    # OTHER GITHUB EVENTS
    # --------------------------------------------------

    return {
        "success": True,
        "event": event,
        "message": "Webhook received and verified. Event not yet processed.",
    }
